const DICTS = { en: EN, it: IT };
let lang = (() => {
  try { return localStorage.getItem('starfall.lang') || (navigator.language || 'en').slice(0, 2); } catch { return 'en'; }
})();
if (!DICTS[lang]) lang = 'en';

export const getLang = () => lang;
export function setLang(l) {
  lang = DICTS[l] ? l : 'en';
  try { localStorage.setItem('starfall.lang', lang); } catch {}
}
export function t(key, vars) {
  let v = DICTS[lang][key] ?? EN[key] ?? key;
  if (Array.isArray(v)) v = v[0];
  if (vars) for (const [k, x] of Object.entries(vars)) v = v.replaceAll(`{${k}}`, x);
  return v;
}
export const desc = (key) => (DICTS[lang][key] || EN[key] || [])[1] || '';
export const errText = (code) => (DICTS[lang].err[code] || EN.err[code] || code);
